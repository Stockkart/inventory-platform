import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import { PHONE_COUNTRY_CODE, PHONE_LOCAL_DIGITS, isValidPhone, normalisePhone } from './phone.js';

/** `fixtures/phones.json`, written by the Java `PhoneNumbersFixtureGeneratorTest` (task 1.2). */
interface PhonesFixture {
  generatedBy: string;
  rule: string;
  localDigits: number;
  countryCode: string;
  cases: { name: string; input: string; normalised: string | null }[];
}

const fixture: PhonesFixture = JSON.parse(
  readFileSync(fileURLToPath(new URL('../fixtures/phones.json', import.meta.url)), 'utf8'),
);

describe('normalisePhone (twin of Java PhoneNumbers.normalise)', () => {
  it('the fixture was generated by the Java side and is not empty', () => {
    expect(fixture.generatedBy).toContain('PhoneNumbersFixtureGeneratorTest');
    expect(fixture.cases.length).toBeGreaterThan(20);
  });

  it('shares the constants with the fixture', () => {
    expect(PHONE_LOCAL_DIGITS).toBe(fixture.localDigits);
    expect(PHONE_COUNTRY_CODE).toBe(fixture.countryCode);
  });

  it('gives the Java answer on every fixture row', () => {
    const mismatches = fixture.cases
      .map(({ name, input, normalised }) => ({
        name,
        input,
        want: normalised,
        got: normalisePhone(input),
      }))
      .filter((row) => row.got !== row.want);
    expect(mismatches).toEqual([]);
  });

  it('accepts a bare 10-digit number and a 91-prefixed one, answering the 10 digits', () => {
    expect(normalisePhone('9876543210')).toBe('9876543210');
    expect(normalisePhone('+91 98765 43210')).toBe('9876543210');
    expect(normalisePhone('919876543210')).toBe('9876543210');
  });

  it('refuses nine or eleven digits, a leading zero, and non-ASCII digits', () => {
    expect(normalisePhone('987654321')).toBeNull();
    expect(normalisePhone('09876543210')).toBeNull();
    expect(normalisePhone('९८७६५४३२१०')).toBeNull();
    expect(normalisePhone('')).toBeNull();
  });

  it('treats null and undefined as empty', () => {
    expect(normalisePhone(null)).toBeNull();
    expect(normalisePhone(undefined)).toBeNull();
    expect(isValidPhone(null)).toBe(false);
  });

  it('isValidPhone agrees with normalisePhone', () => {
    for (const { input, normalised } of fixture.cases) {
      expect(isValidPhone(input)).toBe(normalised !== null);
    }
  });
});
